-- 0048_products_delete_policy.sql
-- إتاحة حذف المنتجات للإدارة — مفيش سياسة حذف كانت موجودة أصلاً، فالحذف
-- كان مرفوض تلقائيًا. الحماية من كسر تاريخ الطلبات القديمة موجودة بالفعل
-- على مستوى الجدول (order_items.product_id قيدها "on delete restrict")،
-- يعني منتج اتباع قبل كده مستحيل يتمسح فعليًا — هيرجع خطأ واضح بدل ما
-- يكسر بيانات الطلبات القديمة، والحل وقتها إنه يوصّف كـ"غير نشط" بدل الحذف.
-- =====================================================================

create policy products_delete_admin on public.products
  for delete using (public.is_admin());
