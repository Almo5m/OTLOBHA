-- 0045_user_sessions_insert_policy.sql
-- السبب الحقيقي وراء "لا توجد جلسات نشطة" دايمًا: الجدول والصفحة وزرار
-- الإنهاء كلهم موجودين، لكن مفيش أي مكان في المشروع كان بيسجّل جلسة
-- فعليًا وقت تسجيل الدخول — ومفيش حتى صلاحية INSERT للجدول ده أصلاً،
-- فحتى لو حد حاول يسجّل جلسة، RLS كانت هترفضها بصمت.
-- =====================================================================

create policy sessions_insert_own on public.user_sessions
  for insert with check (user_id = auth.uid());

-- تحديث لحظي لقائمة الجلسات كمان (نفس فكرة باقي الصفحات)
alter publication supabase_realtime add table public.user_sessions;
